/* Dịch 1 chuỗi (giữ nguyên khoảng trắng 2 đầu). Trả về chính nó nếu chưa có trong từ điển. */
function trs(s){
  if(!I18N.on()||!s||typeof s!=="string")return s;
  const t=s.trim();if(!t)return s;
  let v=I18N.EN[t];
  if(v===undefined){for(const r of I18N.RX){if(r[0].test(t)){v=t.replace(r[0],r[1]);break;}}}
  if(v===undefined||v===t)return s;
  return s.slice(0,s.length-s.trimStart().length)+v+s.slice(s.trimEnd().length);
}
/* Chiều ngược EN -> VI: dùng khi code cũ lưu lại chữ ĐÃ DỊCH rồi ghi trả vào DOM
   (vd bc.js lưu nhãn nút trước khi gửi Google Sheet). Không có nó thì ô đó kẹt tiếng Anh khi bấm về VI. */
function i18nRev(s){
  if(!s||typeof s!=="string")return s;
  if(!I18N._rev){I18N._rev={};for(const k in I18N.EN){const v=I18N.EN[k];if(v&&I18N._rev[v]===undefined)I18N._rev[v]=k;}}
  const t=s.trim();if(!t)return s;
  const v=I18N._rev[t];
  if(v===undefined||v===t)return s;
  return s.slice(0,s.length-s.trimStart().length)+v+s.slice(s.trimEnd().length);
}
/* Bỏ qua vùng không được dịch: <script>/<style>/<textarea> và [data-noi18n].
   Dùng closest() (native, 1 lần/element) thay vì tự lặp lên tổ tiên cho TỪNG text node
   -> quét bảng lớn (Tổng Hợp đại lý vài nghìn dòng) nhanh hơn hẳn. */
function i18nSkip(el){
  const tg=el.nodeName;
  if(tg==="SCRIPT"||tg==="STYLE"||tg==="TEXTAREA")return true;
  return !!(el.closest&&el.closest("script,style,textarea,[data-noi18n]"));
}
function i18nNode(n){
  if(!n.parentElement||i18nSkip(n.parentElement))return;
  if(n.__vi===undefined)n.__vi=n.nodeValue;
  const out=I18N.on()?trs(n.__vi):i18nRev(n.__vi);
  if(n.nodeValue!==out){I18N.busy++;n.nodeValue=out;I18N.busy--;}
  n.__out=n.nodeValue; // dấu vết bản do i18n ghi ra -> observer phân biệt được với chữ mới của app
}
