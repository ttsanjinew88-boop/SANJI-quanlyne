function i18nObserve(){
  new MutationObserver(ms=>{
    if(I18N.busy||!I18N.on())return;
    for(const m of ms){
      // characterData: bỏ qua chính bản dịch mình vừa ghi; chữ MỚI của app thì quên bản gốc cũ rồi dịch lại
      if(m.type==="characterData"){const n=m.target;if(n.__out===n.nodeValue)continue;n.__vi=undefined;i18nNode(n);continue;}
      if(m.type==="attributes"){i18nEl(m.target);continue;}
      m.addedNodes.forEach(n=>{if(n.nodeType===3||n.nodeType===1)i18nWalk(n);});
    }
  }).observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:["placeholder","title","alt"]});
}
